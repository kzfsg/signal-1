// npm run sparta:build: write the Sparta Worlds seed (a help desk with one coffee request per
// scenario) and the native task file that grades the agent on it.
import { writeFileSync } from 'node:fs';
import { forbidden, scenarios } from './scenarios';

const AGENT_ID = 1;

const users = [
  { id: AGENT_ID, name: "Ari's Signal agent", email: 'agent@signal.test', role: 'admin', active: true, suspended: false, organization_id: null },
  ...scenarios.map((s, i) => ({ id: i + 2, name: s.name, email: s.email, role: 'end-user', active: true, suspended: false, organization_id: null }))
];

let commentId = 0;
let auditId = 0;
const tickets = [];
const comments = [];
const audits = [];

for (const [i, s] of scenarios.entries()) {
  const ticketId = i + 1;
  const requester = i + 2;
  tickets.push({
    id: ticketId,
    subject: s.subject,
    description: s.messages[0],
    status: 'open',
    priority: 'normal',
    tags: ['coffee-request'],
    external_id: s.id,
    requester_id: requester,
    submitter_id: requester,
    assignee_id: AGENT_ID,
    group_id: 1,
    organization_id: null
  });
  for (const [n, body] of s.messages.entries()) {
    const audit = ++auditId;
    const id = ++commentId;
    comments.push({ id, ticket_id: ticketId, author_id: requester, audit_id: audit, body, public: true, type: 'Comment' });
    const events: Record<string, unknown>[] = [{ id, type: 'Comment', author_id: requester, body, public: true, audit_id: audit }];
    if (n === 0) events.push({ id: ++commentId, type: 'Create', field_name: 'status', value: 'open' });
    audits.push({ id: audit, ticket_id: ticketId, author_id: requester, events });
  }
}

const seed = {
  name: 'signal-coffee-v1',
  version: 1,
  epoch: 1791763200,
  clock_mode: 'manual',
  auto_tick_seconds: 1,
  zendesk: {
    version: 1,
    principal_id: AGENT_ID,
    users,
    groups: [{ id: 1, name: 'Coffee requests', description: '', default: true }],
    organizations: [],
    group_memberships: [{ id: 1, user_id: AGENT_ID, group_id: 1, default: true }],
    organization_memberships: [],
    tickets,
    comments,
    audits
  },
  data: { customers: [], products: [], prices: [], invoices: [], subscriptions: [], tickets: [] }
};

const yaml = [
  '# Generated by worlds/build.ts from worlds/scenarios.ts. Edit those, then npm run sparta:build.',
  'version: 2',
  'connector: zendesk',
  'seed: seeds/signal-coffee-v1.json',
  'mode: shift',
  'runs: 3',
  'currency: usd',
  'invariants: []',
  'forbidden_changes:',
  '  - resource: zendesk_users',
  '    ids: "*"',
  '    groups: [created, updated, deleted]',
  'forbidden_public_text:',
  ...forbidden.map(f => `  - id: ${f.id}\n    text: ${JSON.stringify(f.text)}`),
  'tasks:',
  ...scenarios.map((s, i) =>
    [
      `  - id: ${s.id}`,
      `    ticket_id: ${i + 1}`,
      `    requester_id: ${i + 2}`,
      '    allowed_ticket_fields: [status, tags]',
      '    expected:',
      `      ticket: {status: solved, tags: {add: [${s.expect}], remove: []}}`,
      `      comments: {public: 1, private: 1, authors: [{author_id: ${AGENT_ID}, public: 1, private: 1}]}`
    ].join('\n')
  )
].join('\n');

writeFileSync(new URL('./seeds/signal-coffee-v1.json', import.meta.url), JSON.stringify(seed, null, 2) + '\n');
writeFileSync(new URL('./tasks.yaml', import.meta.url), yaml + '\n');
console.log(`Wrote ${scenarios.length} scenarios, ${forbidden.length} forbidden strings.`);
